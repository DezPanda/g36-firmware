#!/usr/bin/env python3
"""Turns the tree silhouettes of tree-art/vectorportal-tree-silhouettes-ocal/tree-silhouettes.svg (Open Clipart, public domain)
into treeshapes.h: one 1-bit shape per tree, TS_H pixels tall, for the menu's skyline (g36menu.c, tree_shape_draw).
Needs macOS (qlmanage renders the SVG) and Pillow.  Usage: python3 make_treeshapes.py <svg> <scratch dir> <out .h>"""
import re, subprocess, sys, os
from PIL import Image

TS_H = 192
NAMES = ["round oak", "pagoda", "spruce", "cypress", "maple", "wide oak", "fir"]

svg, scratch, out = sys.argv[1:4]
src = open(svg).read()
head = src[:src.index("<g")]
paths = re.findall(r'<path\s+id="[^"]*"\s+d="([^"]*)"', src, re.S)
assert len(paths) == len(NAMES), len(paths)
os.makedirs(scratch, exist_ok=True)
shapes = []
for i, d in enumerate(paths):
    one = f'{head}<g transform="translate(3.1875 -18.401)"><path d="{d}" fill="#000"/></g></svg>'
    f = os.path.join(scratch, f"tree{i}.svg")
    open(f, "w").write(one)
    subprocess.run(["qlmanage", "-t", "-s", "2600", "-o", scratch, f], check=True, capture_output=True)
    im = Image.open(f + ".png").convert("RGBA")
    a = im.split()[3]
    if a.getextrema()[0] > 250:   # an opaque picture (black on white): the ink is how dark it is
        a = Image.eval(im.convert("L"), lambda v: 255 - v)
    box = a.getbbox()
    a = a.crop(box)
    w = max(1, round(a.width * TS_H / a.height))
    a = a.resize((w, TS_H), Image.BOX)
    bits = a.point(lambda v: 255 if v >= 128 else 0)
    shapes.append((NAMES[i], w, bits))

with open(out, "w") as o:
    o.write("/* Generated by tools/make_treeshapes.py from tree-art/vectorportal-tree-silhouettes-ocal/tree-silhouettes.svg\n"
            " * (Open Clipart, public domain). One 1-bit shape per tree, rows top to bottom, most significant bit first. */\n")
    o.write(f"#define TS_H {TS_H}\n#define TS_N {len(shapes)}\n")
    for i, (name, w, bits) in enumerate(shapes):
        stride = (w + 7) // 8
        o.write(f"/* {name}: {w} x {TS_H} */\nstatic const unsigned char ts_bits{i}[] = {{\n")
        px = bits.load()
        for y in range(TS_H):
            row = []
            for bx in range(stride):
                v = 0
                for k in range(8):
                    x = bx * 8 + k
                    if x < w and px[x, y]:
                        v |= 0x80 >> k
                row.append("0x%02x" % v)
            o.write(" " + ",".join(row) + ",\n")
        o.write("};\n")
    o.write("static const struct { int w; const unsigned char *bits; } ts_shape[TS_N] = {\n")
    for i, (name, w, bits) in enumerate(shapes):
        o.write(f"   {{ {w}, ts_bits{i} }},   /* {name} */\n")
    o.write("};\n")
print("ok", [(n, w) for n, w, _ in shapes])
